import fs from "node:fs";
import vm from "node:vm";
import assert from "node:assert/strict";
import ts from "typescript";

const source = fs.readFileSync(new URL("../src/utils/triageWork.ts", import.meta.url), "utf8");
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const values = new Map();
let blocked = false;
const localStorage = { getItem: key => values.get(key) ?? null, setItem(key, value) { if (blocked) throw Error("quota"); values.set(key, value); } };
const exports = {};
vm.runInNewContext(compiled, { exports, localStorage, URLSearchParams });
const { workQuery, workStorageKey, readTriageWork, writeTriageWork, workIds, completeWorkSample, reconcileWork } = exports;
const plain = value => JSON.parse(JSON.stringify(value));
const state = (id, version = 1) => ({ sample_id: id, triage_version: version, file_hash: `hash-${id}`, triage_policy_version: 1, triage_status: "ok", triage_outdated: false });
let work = { version: 1, datasetId: 7, datasetCreatedAt: "2026-11-07", query: "queue=current_filter&status=ng", sampleIds: [3, 1, 2], completed: {}, skipped: [], currentId: 1, view: "todo", mode: "detail" };
assert.equal(writeTriageWork(work), true);
assert.deepEqual(plain(readTriageWork(7, work.datasetCreatedAt)), work);
assert.equal(readTriageWork(7, "different-database"), null);
assert.equal(readTriageWork(8, work.datasetCreatedAt), null);
work = completeWorkSample(work, state(1));
work.skipped = [2];
assert.deepEqual(plain(workIds(work)), [3]);
assert.deepEqual(plain(workIds({ ...work, view: "skipped" })), [2]);
assert.deepEqual(plain(workIds({ ...work, view: "all" })), [3, 1, 2]);
assert.deepEqual(plain(work.sampleIds), [3, 1, 2]);
assert.equal(writeTriageWork(work), true);
assert.equal(readTriageWork(7, work.datasetCreatedAt).mode, "detail");
const fresh = reconcileWork(work, [state(1), state(2), state(3), state(99)]);
assert.equal(fresh.changed, 0);
assert.deepEqual(plain(fresh.work.sampleIds), [3, 1, 2]);
assert.deepEqual(Object.keys(fresh.work.completed), ["1"]);
const modified = reconcileWork(work, [state(1, 2), state(2)]);
assert.equal(modified.changed, 1);
assert.equal(modified.removed, 1);
assert.deepEqual(Object.keys(modified.work.completed), []);
assert.deepEqual(plain(workIds(modified.work)), [1]);
assert.equal(reconcileWork(work, [{ ...state(1), triage_outdated: true }, state(2), state(3)]).changed, 1);
assert.equal(reconcileWork(work, [{ ...state(1), file_hash: "new" }, state(2), state(3)]).changed, 1);
assert.equal(reconcileWork(work, [{ ...state(1), triage_policy_version: 2 }, state(2), state(3)]).changed, 1);
assert.equal(reconcileWork(work, [{ ...state(1), file_status: "missing" }, state(2), state(3)]).changed, 1);
assert.equal(completeWorkSample(work, { ...state(1), triage_status: "untriaged" }).completed[1], undefined);
const unsafe = workQuery(new URLSearchParams("queue=wrong&status=bogus&defectType=-3&split=bad&back=https://evil.example&review_run=123&sample=22"));
assert.equal(unsafe, "queue=untriaged");
assert.equal(workQuery(new URLSearchParams("queue=current_filter&status=ng&defectType=4&q=needle")), "queue=current_filter&status=ng&defectType=4&q=needle");
for (const corrupt of ["{", "null", "[]", JSON.stringify({ ...work, sampleIds: [-1] }), JSON.stringify({ ...work, sampleIds: Array(10001).fill(1) }), JSON.stringify({ ...work, version: 3 })]) {
  values.set(workStorageKey(7), corrupt);
  assert.equal(readTriageWork(7, work.datasetCreatedAt), null);
}
blocked = true;
assert.equal(writeTriageWork(work), false);
assert.deepEqual(plain(workIds(work)), [3]);
console.log("Triage work checks passed: persistence, identity, fixed scope, skipped views, external edits, deleted records, safe filters, corrupt storage and quota failure.");
